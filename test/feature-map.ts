// The feature map: every feature a person can name, by the words the screen
// uses, with the code and the tests behind it. `test/feature-map.test.ts`
// keeps it true (every browser spec, window and server folder and wire call
// belongs to a feature, and every name here exists); `pnpm feature-map`
// writes `docs/feature-map.md` from it. Plain data: it imports nothing.

/** Groups in the order the window is laid out, then what has no screen. */
export const GROUPS = [
  "Sidebar",
  "Thread",
  "Composer",
  "Images in a chat",
  "Pages",
  "Models",
  "Usage",
  "Pictures",
  "Settings",
  "Library",
  "First run and Ollama",
  "Updates",
  "Voice",
  "Phone",
  "Desktop app",
  "No screen",
  "Across the app",
] as const;

export type Group = (typeof GROUPS)[number];

export type Feature = {
  /** Kebab-case key, unique. */
  readonly id: string;
  /** The words the screen gives it. A feature with no screen uses the changelog's words. */
  readonly name: string;
  readonly group: Group;
  /** One line: what it is for. */
  readonly what: string;
  /** Where a person reaches it. */
  readonly where: string;
  /** Other names for the same thing in the code or older docs. */
  readonly aka?: readonly string[];
  /** Folders or files under `apps/web/src/`. */
  readonly window: readonly string[];
  /** Folders or files under `apps/server/src/`. */
  readonly server: readonly string[];
  /** Folders or files under `apps/desktop/src/`. */
  readonly desktop?: readonly string[];
  /** Folders under `packages/`. */
  readonly packages?: readonly string[];
  /** Methods from the `methods` table in `packages/contracts/src/protocol.ts`. */
  readonly calls: readonly string[];
  /** Channels from the `pushes` table there. */
  readonly pushes: readonly string[];
  /** Browser specs: a bare name is in `test/e2e/`; a path is from the repository root. */
  readonly specs: readonly string[];
  /** `data-testid` of its main controls; a trailing `*` stands for a per-item suffix. */
  readonly testIds?: readonly string[];
};

